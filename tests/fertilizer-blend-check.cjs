const assert=require('node:assert/strict');
const {calculate}=require('../fertilizer-blend.js');
const p=[{name:'MAP',rate:100,N:11,P2O5:52,K2O:0,S:0,price:700},{name:'Urea',rate:150,N:46,P2O5:0,K2O:0,S:0,price:500},{name:'AMS',rate:50,N:21,P2O5:0,K2O:0,S:24,price:400}];
const targets={N:100,P2O5:50,K2O:0,S:15};
const r=calculate(80,targets,p);
assert.deepEqual(r.totals,{N:90.5,P2O5:52,K2O:0,S:12});
assert.deepEqual(r.balance,{N:-9.5,P2O5:2,K2O:0,S:-3});
assert.deepEqual(r.rows.map(x=>x.tons),[4,6,2]);
assert.equal(r.cost,6600);assert.equal(r.costPerAcre,82.5);
assert.equal(calculate(80,targets,[{...p[0],price:null}]).cost,null);
assert.throws(()=>calculate(0,targets,p));
assert.throws(()=>calculate(80,targets,[{...p[0],rate:-1}]));
assert.throws(()=>calculate(80,targets,[{...p[0],N:99}]));
assert.throws(()=>calculate(80,{...targets,S:undefined},p));
console.log('Dry fertilizer blend arithmetic checks passed');
